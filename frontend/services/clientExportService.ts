export function triggerClientBlobDownload(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1500);
}

function pdfSafeText(val: unknown): string {
  if (val === null || val === undefined) return '';
  const str = String(val);
  // Helvetica in jsPDF handles basic ASCII/Latin1 cleanly; replace unsupported non-Latin glyphs safely
  return str.replace(/₹/g, 'INR ').replace(/[^\x20-\x7E\xA0-\xFF]/g, '').trim() || str.replace(/₹/g, 'INR ');
}

function formatCellValue(val: unknown, type: string): string {
  if (val === null || val === undefined) return '-';
  if (type === 'currency') {
    const num = Number(val);
    if (Number.isFinite(num)) {
      return `INR ${num.toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
    }
  }
  if (type === 'number') {
    const num = Number(val);
    if (Number.isFinite(num)) return num.toLocaleString('en-IN');
  }
  return String(val);
}

export async function exportDatasetPdf(
  dataset: ReportDataset,
  options: {
    orientation?: 'portrait' | 'landscape';
    pageSize?: 'a4' | 'letter';
    language?: 'en' | 'bn';
    filename?: string;
    includeHeaderFooter?: boolean;
  } = {}
): Promise<{ blob: Blob; filename: string; fileSizeBytes: number }> {
  const orientation = options.orientation || (dataset.columns.length > 6 ? 'landscape' : 'portrait');
  const doc = new jsPDF({
    orientation,
    unit: 'pt',
    format: options.pageSize || 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const title = pdfSafeText(dataset.title);
  const subtitle = pdfSafeText(dataset.subtitle);

  // Header
  if (options.includeHeaderFooter !== false) {
    doc.setFontSize(14);
    doc.setFont('helvetica', 'bold');
    doc.text('MUN COMPUTER — Enterprise Portal (Version 1.1.0)', 36, 36);
    doc.setFontSize(9);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(100);
    doc.text(`www.muncomputer.org  |  FY: ${dataset.financialYear}  |  Generated By: ${dataset.generatedBy}`, 36, 51);
    doc.setDrawColor(210);
    doc.line(36, 59, pageWidth - 36, 59);
  }

  doc.setTextColor(15);
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.text(title, 36, 80);

  doc.setFontSize(8.5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(90);
  doc.text(`${subtitle}  |  Period: ${pdfSafeText(dataset.dateRangeLabel)}`, 36, 94);

  let cursorY = 108;

  if (dataset.summaryCards && dataset.summaryCards.length > 0) {
    const cardSummary = dataset.summaryCards
      .map((c) => `${pdfSafeText(c.label)}: ${pdfSafeText(c.value)}`)
      .join('   |   ');
    doc.setFontSize(8.5);
    doc.setTextColor(20);
    const wrapped = doc.splitTextToSize(cardSummary, pageWidth - 72);
    doc.text(wrapped, 36, cursorY);
    cursorY += wrapped.length * 11 + 8;
  }

  const head = [dataset.columns.map((c) => pdfSafeText(c.label))];
  const body = dataset.rows.map((r) =>
    dataset.columns.map((c) => pdfSafeText(formatCellValue(r[c.key], c.type)))
  );

  const hasTotals = dataset.totals && Object.keys(dataset.totals).length > 0;
  const foot = hasTotals
    ? [
        dataset.columns.map((c, idx) => {
          if (idx === 0) return 'TOTAL';
          const v = dataset.totals[c.key];
          return v !== undefined ? pdfSafeText(formatCellValue(v, c.type)) : '';
        }),
      ]
    : undefined;

  autoTable(doc, {
    startY: cursorY,
    head,
    body,
    foot,
    theme: 'grid',
    styles: { fontSize: 7.5, cellPadding: 4, overflow: 'linebreak' },
    headStyles: { fillColor: [20, 20, 20], textColor: [255, 255, 255], fontStyle: 'bold' },
    footStyles: { fillColor: [243, 244, 246], textColor: [15, 15, 15], fontStyle: 'bold' },
    margin: { left: 36, right: 36, bottom: 40 },
    didDrawPage: (hookData) => {
      if (options.includeHeaderFooter !== false) {
        const pageH = doc.internal.pageSize.getHeight();
        doc.setFontSize(7.5);
        doc.setTextColor(120);
        doc.text(
          `Generated ${new Date(dataset.generatedAt).toLocaleString('en-IN')} IST  ·  Page ${hookData.pageNumber}`,
          36,
          pageH - 18
        );
      }
    },
  });

  const blob = doc.output('blob');
  const filename = options.filename || `MUN_${dataset.reportKey}_${Date.now()}.pdf`;
  triggerClientBlobDownload(blob, filename);
  return { blob, filename, fileSizeBytes: blob.size };
}

export async function exportCombinedPdf(
  datasets: ReportDataset[],
  options: { orientation?: 'portrait' | 'landscape'; pageSize?: 'a4' | 'letter'; filename?: string } = {}
): Promise<{ blob: Blob; filename: string; fileSizeBytes: number }> {
  const orientation = options.orientation || 'landscape';
  const doc = new jsPDF({
    orientation,
    unit: 'pt',
    format: options.pageSize || 'a4',
  });

  datasets.forEach((ds, index) => {
    if (index > 0) doc.addPage();
    doc.setFontSize(13);
    doc.setFont('helvetica', 'bold');
    doc.text(`MUN COMPUTER — ${pdfSafeText(ds.title)}`, 36, 38);
    doc.setFontSize(8.5);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(90);
    doc.text(
      `Bundle Item ${index + 1}/${datasets.length}  |  ${pdfSafeText(ds.subtitle)}  |  Period: ${pdfSafeText(ds.dateRangeLabel)}`,
      36,
      54
    );

    autoTable(doc, {
      startY: 66,
      head: [ds.columns.map((c) => pdfSafeText(c.label))],
      body: ds.rows.map((r) => ds.columns.map((c) => pdfSafeText(formatCellValue(r[c.key], c.type)))),
      theme: 'grid',
      styles: { fontSize: 7.5, cellPadding: 4, overflow: 'linebreak' },
      headStyles: { fillColor: [20, 20, 20], textColor: [255, 255, 255] },
      margin: { left: 36, right: 36 },
    });
  });

  const blob = doc.output('blob');
  const filename = options.filename || `MUN_Executive_Bundle_${new Date().toISOString().slice(0, 10)}.pdf`;
  triggerClientBlobDownload(blob, filename);
  return { blob, filename, fileSizeBytes: blob.size };
}

export function exportDatasetExcel(
  dataset: ReportDataset,
  filename?: string
): { blob: Blob; filename: string; fileSizeBytes: number } {
  const wb = XLSX.utils.book_new();
  const headers = dataset.columns.map((c) => c.label);
  const rowsAoA = dataset.rows.map((r) => dataset.columns.map((c) => r[c.key] ?? ''));
  if (dataset.totals && Object.keys(dataset.totals).length > 0) {
    rowsAoA.push(
      dataset.columns.map((c, idx) => (idx === 0 ? 'TOTAL' : dataset.totals[c.key] ?? ''))
    );
  }
  const sheetData = [
    [dataset.title, '', `FY: ${dataset.financialYear}`, `Period: ${dataset.dateRangeLabel}`],
    [`Generated By: ${dataset.generatedBy}`, `Generated At: ${dataset.generatedAt}`],
    [],
    headers,
    ...rowsAoA,
  ];
  const ws = XLSX.utils.aoa_to_sheet(sheetData);
  XLSX.utils.book_append_sheet(wb, ws, 'ReportData');

  if (dataset.summaryCards && dataset.summaryCards.length > 0) {
    const summaryWs = XLSX.utils.json_to_sheet(
      dataset.summaryCards.map((c) => ({ Metric: c.label, Value: c.value, Note: c.note || '' }))
    );
    XLSX.utils.book_append_sheet(wb, summaryWs, 'KPI_Summary');
  }

  const out = XLSX.write(wb, { bookType: 'xlsx', type: 'array' });
  const blob = new Blob([out], {
    type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  });
  const finalName = filename || `MUN_${dataset.reportKey}_${Date.now()}.xlsx`;
  triggerClientBlobDownload(blob, finalName);
  return { blob, filename: finalName, fileSizeBytes: blob.size };
}

export function exportDatasetCsv(
  dataset: ReportDataset,
  filename?: string
): { blob: Blob; filename: string; fileSizeBytes: number } {
  const headers = dataset.columns.map((c) => c.label);
  const lines = [
    headers.map((h) => `"${h.replace(/"/g, '""')}"`).join(','),
    ...dataset.rows.map((row) =>
      dataset.columns
        .map((c) => `"${String(row[c.key] ?? '').replace(/"/g, '""')}"`)
        .join(',')
    ),
  ];
  const blob = new Blob([`\ufeff${lines.join('\n')}`], { type: 'text/csv;charset=utf-8;' });
  const finalName = filename || `MUN_${dataset.reportKey}_${Date.now()}.csv`;
  triggerClientBlobDownload(blob, finalName);
  return { blob, filename: finalName, fileSizeBytes: blob.size };
}

export function exportAuditChainCsv(entries: TamperAuditEntry[]): string {
  const headers = [
    'Audit UUID',
    'Timestamp',
    'User ID',
    'Role',
    'Action Type',
    'Module',
    'Record ID',
    'Result',
    'IP Address',
    'Device Info',
    'Previous Hash',
    'Entry Hash',
  ];
  const lines = [
    headers.map((h) => `"${h}"`).join(','),
    ...entries.map((e) =>
      [
        e.auditUuid,
        e.createdAt,
        e.userId,
        e.userRole,
        e.actionType,
        e.module,
        e.recordId,
        e.actionResult,
        e.ipAddress,
        e.deviceInfo,
        e.previousHash,
        e.entryHash,
      ]
        .map((v) => `"${String(v ?? '').replace(/"/g, '""')}"`)
        .join(',')
    ),
  ];
  const blob = new Blob([`\ufeff${lines.join('\n')}`], { type: 'text/csv;charset=utf-8;' });
  const filename = `MUN_Audit_HashChain_${new Date().toISOString().slice(0, 10)}.csv`;
  triggerClientBlobDownload(blob, filename);
  return filename;
}

