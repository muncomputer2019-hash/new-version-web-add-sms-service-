import ExcelJS from 'exceljs';
import { CompanyProfileSettings } from '../phase03Types.js';
import { formatDateTimeISTServer } from './reportDataEngine.js';
import { ExcelExportOptions, ReportDataset } from './reportTypes.js';

function sanitizeCsvCell(value: unknown): string {
  const raw = value === null || value === undefined ? '' : String(value);
  // Neutralize CSV formula injection (Excel/Sheets DDE)
  const neutralized = /^[=+\-@\t\r]/.test(raw) ? `'${raw}` : raw;
  if (/[",\n\r]/.test(neutralized)) {
    return `"${neutralized.replace(/"/g, '""')}"`;
  }
  return neutralized;
}

export function validateDatasetForExport(dataset: ReportDataset): void {
  if (!dataset || !Array.isArray(dataset.columns) || dataset.columns.length === 0) {
    throw new Error('Export failed: report columns are missing or empty.');
  }
  if (!Array.isArray(dataset.rows)) {
    throw new Error('Export failed: report dataset rows are corrupted.');
  }
}

export function generateCsvBuffer(dataset: ReportDataset, language: 'en' | 'bn' = 'en'): Buffer {
  validateDatasetForExport(dataset);
  const headers = dataset.columns.map((c) =>
    sanitizeCsvCell(language === 'bn' && c.labelBn ? `${c.labelBn} (${c.label})` : c.label)
  );
  const lines = [headers.join(',')];
  for (const row of dataset.rows) {
    const cells = dataset.columns.map((col) => sanitizeCsvCell(row[col.key] ?? ''));
    lines.push(cells.join(','));
  }
  // UTF-8 BOM ensures Excel decodes Bengali & INR symbols cleanly
  return Buffer.from('\uFEFF' + lines.join('\r\n'), 'utf8');
}

function getExcelColLetter(colIndex1Based: number): string {
  let n = colIndex1Based;
  let s = '';
  while (n > 0) {
    const mod = (n - 1) % 26;
    s = String.fromCharCode(65 + mod) + s;
    n = Math.floor((n - mod) / 26);
  }
  return s;
}

export async function generateExcelBuffer(
  dataset: ReportDataset,
  company: CompanyProfileSettings,
  options: ExcelExportOptions = {}
): Promise<Buffer> {
  validateDatasetForExport(dataset);

  const wb = new ExcelJS.Workbook();
  wb.creator = company.companyName || 'MUN COMPUTER BUSINESS MANAGER';
  wb.created = new Date();
  wb.modified = new Date();

  const isBn = options.language === 'bn';

  // --------------------------------------------------------------------------
  // Worksheet 1: Executive Summary
  // --------------------------------------------------------------------------
  if (options.includeSummarySheet !== false) {
    const summaryWs = wb.addWorksheet('Executive Summary', {
      views: [{ showGridLines: true }],
    });
    summaryWs.columns = [
      { header: 'Field', key: 'field', width: 30 },
      { header: 'Value', key: 'value', width: 52 },
      { header: 'Notes', key: 'notes', width: 42 },
    ];

    summaryWs.mergeCells('A1:C1');
    const titleCell = summaryWs.getCell('A1');
    titleCell.value = `${company.companyName || 'MUN COMPUTER'} — ${
      isBn && dataset.titleBn ? `${dataset.titleBn} (${dataset.title})` : dataset.title
    }`;
    titleCell.font = { name: 'Calibri', size: 14, bold: true, color: { argb: 'FFFFFFFF' } };
    titleCell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF0F172A' } };
    titleCell.alignment = { vertical: 'middle', horizontal: 'left', indent: 1 };
    summaryWs.getRow(1).height = 28;

    const metaRows: Array<[string, string | number, string]> = [
      ['Company Name', company.companyName, 'Master Company Settings'],
      [
        'Address',
        [company.addressLine, company.postOffice, company.policeStation, company.district, company.stateName, company.pinCode]
          .filter(Boolean)
          .join(', '),
        'Registered Branch',
      ],
      ['Contact Mobile / WhatsApp', company.mobile || company.whatsapp || '—', company.email || ''],
      ['Financial Year', dataset.financialYear, 'April to March (Asia/Kolkata)'],
      ['Date Range Filter', dataset.dateRangeLabel, dataset.subtitle],
      ['Total Records Exported', dataset.rows.length, `Source total: ${dataset.totalRowsBeforeLimit}`],
      ['Generated At', dataset.generatedAt, `Generated By: ${dataset.generatedBy}`],
      ['Currency & Grouping', 'INR (₹#,##,##0.00)', 'Indian Numbering System'],
    ];

    if (dataset.summaryCards) {
      dataset.summaryCards.forEach((sc) => {
        metaRows.push([sc.label, sc.value, sc.note ?? 'Verified Live Figure']);
      });
    }
    if (dataset.notes) {
      dataset.notes.forEach((n, idx) => {
        metaRows.push([`Disclosure Note ${idx + 1}`, n, 'Compliance / Accounting Rule']);
      });
    }

    metaRows.forEach(([f, v, n]) => {
      const row = summaryWs.addRow({ field: f, value: v, notes: n });
      row.getCell(1).font = { bold: true };
    });
  }

  // --------------------------------------------------------------------------
  // Worksheet 2: Report Data (Formulas, Currency/Date Formatting, Filters)
  // --------------------------------------------------------------------------
  const dataWs = wb.addWorksheet('Report Data', {
    views: [{ state: 'frozen', ySplit: 4 }],
  });

  dataWs.mergeCells(1, 1, 1, Math.max(dataset.columns.length, 1));
  const banner = dataWs.getCell(1, 1);
  banner.value = `${company.companyName} | ${dataset.title} | ${dataset.dateRangeLabel} | ${formatDateTimeISTServer(new Date())}`;
  banner.font = { bold: true, size: 11, color: { argb: 'FF0F172A' } };
  banner.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF1F5F9' } };
  dataWs.getRow(1).height = 22;

  dataWs.getRow(2).values = [`Subtitle: ${dataset.subtitle} | FY: ${dataset.financialYear}`];
  dataWs.getRow(2).font = { italic: true, size: 9, color: { argb: 'FF475569' } };

  const headerRowIdx = 4;
  const headerRow = dataWs.getRow(headerRowIdx);
  headerRow.height = 24;

  dataset.columns.forEach((col, idx) => {
    const cell = headerRow.getCell(idx + 1);
    cell.value = isBn && col.labelBn ? `${col.labelBn} (${col.label})` : col.label;
    cell.font = { bold: true, size: 10, color: { argb: 'FFFFFFFF' } };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF0F172A' } };
    cell.alignment = { vertical: 'middle', horizontal: col.align ?? 'left' };
    cell.border = {
      top: { style: 'thin', color: { argb: 'FFCBD5E1' } },
      bottom: { style: 'thin', color: { argb: 'FFCBD5E1' } },
    };
  });

  const dataStartRow = headerRowIdx + 1;
  dataset.rows.forEach((rowObj, rIdx) => {
    const row = dataWs.getRow(dataStartRow + rIdx);
    const isSubtotal =
      typeof rowObj[dataset.columns[0]?.key] === 'string' &&
      String(rowObj[dataset.columns[0].key]).startsWith('Subtotal');

    dataset.columns.forEach((col, cIdx) => {
      const cell = row.getCell(cIdx + 1);
      const raw = rowObj[col.key];
      if ((col.type === 'currency' || col.type === 'number') && raw !== null && raw !== undefined && raw !== '') {
        const num = Number(raw);
        cell.value = Number.isFinite(num) ? num : String(raw);
        if (col.type === 'currency') {
          cell.numFmt = '₹#,##,##0.00;[Red]-₹#,##,##0.00;"-"';
        } else {
          cell.numFmt = '#,##,##0.##';
        }
        cell.alignment = { horizontal: 'right', vertical: 'middle' };
      } else {
        const text = raw === null || raw === undefined ? '' : String(raw);
        cell.value = /^[=+\-@\t\r]/.test(text) ? `'${text}` : text;
        cell.alignment = { horizontal: col.align ?? 'left', vertical: 'middle' };
      }
      if (isSubtotal) {
        cell.font = { bold: true };
        cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFE2E8F0' } };
      } else if (rIdx % 2 === 1) {
        cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF8FAFC' } };
      }
    });
  });

  const dataEndRow = dataStartRow + Math.max(dataset.rows.length - 1, 0);

  // Real Excel SUM & AVERAGE formula rows at the bottom (excluding subtotal rows via plain dataset slice if no subtotals)
  const hasSubtotalRows = dataset.rows.some(
    (r) =>
      typeof r[dataset.columns[0]?.key] === 'string' &&
      String(r[dataset.columns[0].key]).startsWith('Subtotal')
  );

  if (dataset.rows.length > 0) {
    const totalRowIdx = dataEndRow + 1;
    const avgRowIdx = dataEndRow + 2;
    const totalRow = dataWs.getRow(totalRowIdx);
    const avgRow = dataWs.getRow(avgRowIdx);

    totalRow.getCell(1).value = 'GRAND TOTAL (Excel Formula)';
    totalRow.getCell(1).font = { bold: true };
    avgRow.getCell(1).value = 'AVERAGE (Excel Formula)';
    avgRow.getCell(1).font = { bold: true, italic: true };

    dataset.columns.forEach((col, cIdx) => {
      const colLetter = getExcelColLetter(cIdx + 1);
      const tCell = totalRow.getCell(cIdx + 1);
      const aCell = avgRow.getCell(cIdx + 1);
      if (col.type === 'currency' || col.type === 'number') {
        const serverVal = Number(dataset.totals[col.key] ?? 0);
        if (hasSubtotalRows) {
          // Use SUMIF excluding Subtotal text rows so double counting never occurs
          const firstColLetter = getExcelColLetter(1);
          tCell.value = {
            formula: `SUMIF(${firstColLetter}${dataStartRow}:${firstColLetter}${dataEndRow},"<>Subtotal*",${colLetter}${dataStartRow}:${colLetter}${dataEndRow})`,
            result: serverVal,
          };
        } else {
          tCell.value = {
            formula: `SUM(${colLetter}${dataStartRow}:${colLetter}${dataEndRow})`,
            result: serverVal,
          };
        }
        aCell.value = {
          formula: `AVERAGE(${colLetter}${dataStartRow}:${colLetter}${dataEndRow})`,
          result: Number((serverVal / Math.max(dataset.rows.length, 1)).toFixed(2)),
        };
        const fmt = col.type === 'currency' ? '₹#,##,##0.00' : '#,##,##0.##';
        tCell.numFmt = fmt;
        aCell.numFmt = fmt;
        tCell.font = { bold: true };
        aCell.font = { italic: true };
      }
      tCell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFE2E8F0' } };
    });
  }

  // Auto column widths
  dataset.columns.forEach((col, cIdx) => {
    let maxLen = col.label.length + 4;
    for (const r of dataset.rows.slice(0, 250)) {
      const len = String(r[col.key] ?? '').length;
      if (len > maxLen) maxLen = len;
    }
    dataWs.getColumn(cIdx + 1).width = Math.min(Math.max(maxLen + 3, 14), 46);
  });

  // AutoFilter on header row
  dataWs.autoFilter = {
    from: { row: headerRowIdx, column: 1 },
    to: { row: headerRowIdx, column: dataset.columns.length },
  };

  // Conditional Formatting highlighting Status 'Rejected'/'Cancelled'/'Overdue' or high due
  const statusColIdx = dataset.columns.findIndex((c) => c.type === 'status');
  if (statusColIdx >= 0 && dataset.rows.length > 0) {
    const colLetter = getExcelColLetter(statusColIdx + 1);
    dataWs.addConditionalFormatting({
      ref: `${colLetter}${dataStartRow}:${colLetter}${dataEndRow}`,
      rules: [
        {
          type: 'containsText',
          operator: 'containsText',
          text: 'Rejected',
          priority: 1,
          style: {
            font: { color: { argb: 'FF991B1B' }, bold: true },
            fill: { type: 'pattern', pattern: 'solid', bgColor: { argb: 'FFFEE2E2' } },
          },
        },
        {
          type: 'containsText',
          operator: 'containsText',
          text: 'Completed',
          priority: 2,
          style: {
            font: { color: { argb: 'FF166534' }, bold: true },
            fill: { type: 'pattern', pattern: 'solid', bgColor: { argb: 'FFDCFCE7' } },
          },
        },
      ],
    });
  }

  // --------------------------------------------------------------------------
  // Worksheet 3: Pivot Ready Data
  // --------------------------------------------------------------------------
  if (options.includePivotSheet !== false) {
    const pivotWs = wb.addWorksheet('Pivot Ready Data');
    const pivotHeaders = ['Report Key', 'Financial Year', ...dataset.columns.map((c) => c.label)];
    pivotWs.addRow(pivotHeaders).font = { bold: true };
    dataset.rows.forEach((r) => {
      if (
        typeof r[dataset.columns[0]?.key] === 'string' &&
        String(r[dataset.columns[0].key]).startsWith('Subtotal')
      ) {
        return;
      }
      pivotWs.addRow([
        dataset.reportKey,
        dataset.financialYear,
        ...dataset.columns.map((c) => r[c.key] ?? ''),
      ]);
    });
    pivotHeaders.forEach((_, idx) => {
      pivotWs.getColumn(idx + 1).width = 20;
    });
  }

  // --------------------------------------------------------------------------
  // Worksheet 4: Charts & Series Summary
  // --------------------------------------------------------------------------
  if (options.includeChartSheet !== false) {
    const chartWs = wb.addWorksheet('Charts & Series');
    chartWs.addRow(['Metric / Column', 'Total Value', 'Average Per Row']).font = { bold: true };
    const numericCols = dataset.columns.filter((c) => c.type === 'currency' || c.type === 'number');
    numericCols.forEach((col, idx) => {
      const val = Number(dataset.totals[col.key] ?? 0);
      const avg = dataset.rows.length > 0 ? Number((val / dataset.rows.length).toFixed(2)) : 0;
      const r = chartWs.addRow([col.label, val, avg]);
      if (col.type === 'currency') {
        r.getCell(2).numFmt = '₹#,##,##0.00';
        r.getCell(3).numFmt = '₹#,##,##0.00';
      }
      if (idx === 0) {
        chartWs.getCell('E2').value = 'Note: Select columns A-C in Excel to insert native PivotChart or Bar Chart.';
      }
    });
    chartWs.getColumn(1).width = 32;
    chartWs.getColumn(2).width = 22;
    chartWs.getColumn(3).width = 22;
  }

  const arrayBuffer = await wb.xlsx.writeBuffer();
  return Buffer.from(arrayBuffer);
}
