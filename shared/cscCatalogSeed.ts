export function buildInitialCscServices(nowIso = new Date().toISOString()): CscService[] {
  const list: CscService[] = [];
  let seq = 1;

  for (const cat of RAW_CSC_CATALOG) {
    for (const item of cat.items) {
      const numStr = String(seq).padStart(4, '0');
      list.push({
        id: `CSRV-${numStr}`,
        code: `${cat.code}-${numStr}`,
        categoryId: cat.id,
        categoryName: cat.name,
        subGroup: item.subGroup,
        name: item.name,
        description: item.subGroup
          ? `${cat.name} · ${item.subGroup} — ${item.name}`
          : `${cat.name} — ${item.name}`,
        // CRITICAL: Blank rates on initial install (Part 4 Rule 1 & 2)
        serviceCharge: null,
        govtFee: null,
        totalAmount: null,
        unitType: null,
        rateConfigured: false,
        effectiveDate: null,
        requiredDocuments: ['Applicant ID Proof (Masked Aadhaar / Voter / PAN)'],
        availability: 'Available',
        active: true,
        moduleTag: cat.moduleTag,
        createdAt: nowIso,
        updatedAt: nowIso,
        updatedBy: 'SYSTEM_SEED',
      });
      seq++;
    }
  }

  // Part 2: Dedicated Ayushman Bharat PM-JAY Module (30 services) attached under CAT-02 or PMJAY module filter
  for (const pmjayName of RAW_PMJAY_SERVICES) {
    const numStr = String(seq).padStart(4, '0');
    list.push({
      id: `PMJAY-${numStr}`,
      code: `PMJAY-${numStr}`,
      categoryId: 'CAT-02',
      categoryName: 'Ayushman Bharat PM-JAY',
      subGroup: 'Ayushman Bharat PM-JAY Module',
      name: pmjayName,
      description: `Ayushman Bharat PM-JAY — ${pmjayName}. Only officially supported PM-JAY authentication methods enabled.`,
      // CRITICAL: Blank rates on initial install
      serviceCharge: null,
      govtFee: null,
      totalAmount: null,
      unitType: null,
      rateConfigured: false,
      effectiveDate: null,
      requiredDocuments: ['Aadhaar Card (Masked)', 'Ration / SECC Family ID'],
      availability: 'Available',
      active: true,
      moduleTag: 'PMJAY',
      createdAt: nowIso,
      updatedAt: nowIso,
      updatedBy: 'SYSTEM_SEED',
    });
    seq++;
  }

  return list;
}

